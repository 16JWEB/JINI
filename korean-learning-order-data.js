  if (Array.isArray(window.KOREAN_EXPRESSIONS)) window.KOREAN_EXPRESSIONS.splice(0, originalExpressions.length, ...orderedExpressions);

  function filtered(items, query) {
    const q = String(query || "").trim().toLocaleLowerCase("ko");
    return items.filter(function (item) {
      const other = (item.otherSenses || []).map(function (sense) { return sense.meaning; }).join(" ");
      return (item.word + " " + item.meaning + " " + item.example + " " + item.exampleKo + " " + other)
        .toLocaleLowerCase("ko").includes(q);
    });
  }
  function updateStored(key, update) {
    try {
      const raw = localStorage.getItem(key);
      if (!raw) return;
      const value = JSON.parse(raw);
      if (!value || typeof value !== "object" || Array.isArray(value)) return;
      if (update(value)) localStorage.setItem(key, JSON.stringify(value));
    } catch (_) { /* Keep unreadable or unwritable records intact; retry on a later load. */ }
  }
