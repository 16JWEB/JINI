  const VERSION = 1;
  const PAGE_SIZE = 10;
  const originalWords = (window.KOREAN_WORDS || []).slice();
  const originalExpressions = (window.KOREAN_EXPRESSIONS || []).slice();
  function arrange(items, groups) {
    const byWord = new Map(items.map(function (item) { return [item.word, item]; }));
    const seen = new Set(), result = [];
    Object.values(groups).forEach(function (group) {
      group.forEach(function (word) {
        const item = byWord.get(word);
        if (item && !seen.has(item)) { seen.add(item); result.push(item); }
      });
    });
    // Future additions remain available even before their curriculum is reviewed.
    items.forEach(function (item) { if (!seen.has(item)) { seen.add(item); result.push(item); } });
    if (result.length !== items.length || new Set(result).size !== items.length)
      throw new Error("Korean curriculum integrity check failed");
    return result;
  }
